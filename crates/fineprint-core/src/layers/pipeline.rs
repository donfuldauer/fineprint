//! Evaluation through layers 1a-7d (REQ-LAYER-001, REQ-LAYER-002, CR 613.1-613.5).
//!
//! [`evaluate`], [`evaluate_with_order`] and [`evaluate_all`] run one layer-major board pass
//! ([`super::board`]): every object of the universe (`env.objects()` sorted and de-duplicated,
//! with the object asked for, restricted to objects with a base) advances through each layer
//! together, so a characteristic-defining power or toughness is evaluated with an
//! [`EvaluatedView`] of every object after layers 1-6 (CR 604.3, 613.4a, 613.5), and the
//! existence of a static effect generated by another object is asked with that object's state
//! ([`LayerEnvironment::generating_ability_exists`], CR 613.8a, 611.3, 113.6). The ordering
//! within a layer, the dependency trial included (CR 613.8a), is still judged on the object under
//! evaluation only, and a selector ([`LayerEnvironment::matches`]) sees only
//! [`MatchContext::candidate_view`]. `evaluate(id)` equals `evaluate_all()[id]` whenever `id` is
//! one of `env.objects()`.

